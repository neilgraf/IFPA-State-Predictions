"""
Flask app serving the prediction GUI and the simulation API.

Run it from the repo root:

    python backend/server.py

then open http://127.0.0.1:5000/.
"""

import json
import os
import sys

# Allow `python backend/server.py` (not just `python -m backend.server`) by
# putting the repo root on the import path before the backend.* imports below.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from flask import Flask, jsonify, request, send_from_directory

from backend.models.bracket_definitions import MAX_PLAYERS, SUPPORTED_SIZES, build_bracket
from backend.models.player import Player
from backend.models.players_data import DATASETS
from backend.models.tournament import BracketTournament

FRONTEND_DIR = os.path.join(REPO_ROOT, "frontend")
PREDICTIONS_PATH = os.path.join(REPO_ROOT, "backend", "data", "predictions.json")

DEFAULT_RATING = 1500
MIN_RATING = 0
MAX_RATING = 4000
MAX_SIMULATIONS = 200000
ALLOWED_BEST_OF = (1, 3, 5, 7, 9)

app = Flask(__name__, static_folder=FRONTEND_DIR, static_url_path="")


class InvalidRoster(ValueError):
    """Raised when a submitted roster can't be turned into a bracket."""


@app.route("/")
def index():
    return send_from_directory(FRONTEND_DIR, "index.html")


@app.route("/api/config")
def config():
    """Everything the setup GUI needs to render itself."""
    return jsonify({
        "supported_sizes": SUPPORTED_SIZES,
        "max_players": MAX_PLAYERS,
        "default_rating": DEFAULT_RATING,
        "allowed_best_of": list(ALLOWED_BEST_OF),
        "max_simulations": MAX_SIMULATIONS,
        "datasets": {
            key: [{"name": p.name, "rating": p.rating} for p in sorted(roster, key=lambda p: p.seed)]
            for key, roster in DATASETS.items()
        },
    })


@app.route("/api/predictions")
def predictions():
    """The last roster generated by generate_predictions.py, if there is one."""
    try:
        with open(PREDICTIONS_PATH) as f:
            return jsonify(json.load(f))
    except FileNotFoundError:
        return jsonify({"error": "No saved predictions. Run generate_predictions.py first."}), 404
    except json.JSONDecodeError:
        return jsonify({"error": "predictions.json is not valid JSON."}), 500


def _parse_players(raw_players):
    """Turns the GUI's roster payload into {seed: Player}, seeded by list order."""
    if not isinstance(raw_players, list):
        raise InvalidRoster("'players' must be a list.")
    if len(raw_players) < 2:
        raise InvalidRoster("A bracket needs at least 2 players.")
    if len(raw_players) > MAX_PLAYERS:
        raise InvalidRoster(f"A bracket supports at most {MAX_PLAYERS} players.")

    players = {}
    for index, entry in enumerate(raw_players):
        seed = index + 1
        if isinstance(entry, str):
            entry = {"name": entry}
        if not isinstance(entry, dict):
            raise InvalidRoster(f"Seed {seed}: expected a name or a name/rating object.")

        name = str(entry.get("name", "")).strip()
        if not name:
            raise InvalidRoster(f"Seed {seed} is missing a name.")

        rating = entry.get("rating")
        if rating is None or rating == "":
            rating = DEFAULT_RATING
        try:
            rating = float(rating)
        except (TypeError, ValueError):
            raise InvalidRoster(f"Seed {seed} ({name}): rating '{rating}' is not a number.")
        if not MIN_RATING <= rating <= MAX_RATING:
            raise InvalidRoster(
                f"Seed {seed} ({name}): rating must be between {MIN_RATING} and {MAX_RATING}."
            )

        players[seed] = Player(name, rating, seed)
    return players


def _parse_options(payload):
    simulations = payload.get("simulations", 10000)
    try:
        simulations = int(simulations)
    except (TypeError, ValueError):
        raise InvalidRoster("'simulations' must be a whole number.")
    if not 1 <= simulations <= MAX_SIMULATIONS:
        raise InvalidRoster(f"'simulations' must be between 1 and {MAX_SIMULATIONS}.")

    best_of = payload.get("best_of", 7)
    try:
        best_of = int(best_of)
    except (TypeError, ValueError):
        raise InvalidRoster("'best_of' must be a whole number.")
    if best_of not in ALLOWED_BEST_OF:
        raise InvalidRoster(f"'best_of' must be one of {', '.join(map(str, ALLOWED_BEST_OF))}.")

    rng_seed = payload.get("seed")
    if rng_seed in ("", None):
        rng_seed = None
    else:
        try:
            rng_seed = int(rng_seed)
        except (TypeError, ValueError):
            raise InvalidRoster("'seed' must be a whole number, or left blank.")

    return simulations, best_of, rng_seed


@app.route("/api/simulate", methods=["POST"])
def simulate():
    """
    Runs a bracket from a roster submitted by the GUI.

    Request body:
        {
          "players": [{"name": "...", "rating": 1700}, ...],  # in seed order
          "simulations": 10000,
          "best_of": 7,
          "seed": null
        }
    """
    payload = request.get_json(silent=True)
    if payload is None:
        return jsonify({"error": "Request body must be JSON."}), 400

    try:
        players = _parse_players(payload.get("players"))
        simulations, best_of, rng_seed = _parse_options(payload)
        slots = build_bracket(len(players))
    except InvalidRoster as exc:
        return jsonify({"error": str(exc)}), 400
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400

    tournament = BracketTournament(players, slots, best_of=best_of)
    results = tournament.run(num_simulations=simulations, seed=rng_seed)

    return jsonify({
        "players": len(players),
        "bracket_size": len(slots),
        "byes": sum(1 for slot in slots if slot is None),
        "rounds": tournament.round_labels,
        "best_of": best_of,
        "simulations": simulations,
        "seed": rng_seed,
        "results": results,
    })


if __name__ == "__main__":
    app.run(debug=True)
